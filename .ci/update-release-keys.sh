#!/usr/bin/env bash
# Regenerates release-keys/keys.asc, the Node.js release signing keys fnm
# trusts, from https://github.com/nodejs/release-keys. Review the diff
# (new fingerprints especially) before committing it.

set -euo pipefail

cd "$(dirname "$0")/.."

URL="https://codeload.github.com/nodejs/release-keys/tar.gz/refs/heads/main"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

curl -fsSL "$URL" -o "$TMP/release-keys.tar.gz"
# git stops reading after the header, so keep gzip out of `pipefail`.
COMMIT="$(git get-tar-commit-id < <(gzip -dc "$TMP/release-keys.tar.gz"))"
[[ "$COMMIT" =~ ^[0-9a-f]{40}$ ]] || {
  echo "Can't read the source commit from the tarball" >&2
  exit 1
}
mkdir "$TMP/src"
tar -xzf "$TMP/release-keys.tar.gz" -C "$TMP/src" --strip-components=1

KEYS=("$TMP"/src/keys/*.asc)

{
  echo "# Node.js release signing keys, from https://github.com/nodejs/release-keys"
  echo "# Source commit: $COMMIT"
  echo "# Keys: ${#KEYS[@]}"
  echo "# Generated by .ci/update-release-keys.sh. Do not edit by hand."
  for key in "${KEYS[@]}"; do
    echo
    # `awk 1` ends every file with a newline, so no END line can run into
    # the next BEGIN line.
    awk 1 "$key"
  done
} >release-keys/keys.asc

cp "$TMP/src/LICENSE.md" release-keys/LICENSE.md

# The README lists the active releasers' keys between these markers.
ACTIVE=($(sed -n '/<!-- Active releasers keys -->/,/<!-- \/Active releasers keys -->/p' \
  "$TMP/src/README.md" | grep -oE '[0-9A-F]{40}' | sort -u))
[[ ${#ACTIVE[@]} -gt 0 ]] || {
  echo "Can't find the active releasers in the release-keys README" >&2
  exit 1
}
{
  echo "# Primary keys of the active Node.js releasers, from the nodejs/release-keys README."
  echo "# Source commit: $COMMIT"
  echo "# Generated by .ci/update-release-keys.sh. Do not edit by hand."
  printf '%s\n' "${ACTIVE[@]}"
} >release-keys/active.txt

# Adds the releases that release-keys/signers.txt lacks, each checked with
# the keys above. It warns about a retired key that signs no release.
cargo test --quiet --bin fnm release_keys::update::update_signers -- \
  --ignored --exact --nocapture

echo "release-keys/keys.asc: ${#KEYS[@]} keys, ${#ACTIVE[@]} active, from nodejs/release-keys@$COMMIT"
