#!/usr/bin/env bash
# Regenerates release-keys/keys.asc, the Node.js release signing keys fnm
# trusts, from https://github.com/nodejs/release-keys. Review the diff
# (new fingerprints especially) before committing it.

set -euo pipefail

cd "$(dirname "$0")/.."

URL="https://codeload.github.com/nodejs/release-keys/tar.gz/refs/heads/main"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

curl -fsSL "$URL" -o "$TMP/release-keys.tar.gz"
# git stops reading after the header, so keep gzip out of `pipefail`.
COMMIT="$(git get-tar-commit-id < <(gzip -dc "$TMP/release-keys.tar.gz"))"
[[ "$COMMIT" =~ ^[0-9a-f]{40}$ ]] || {
  echo "Can't read the source commit from the tarball" >&2
  exit 1
}
mkdir "$TMP/src"
tar -xzf "$TMP/release-keys.tar.gz" -C "$TMP/src" --strip-components=1

KEYS=("$TMP"/src/keys/*.asc)

{
  echo "# Node.js release signing keys, from https://github.com/nodejs/release-keys"
  echo "# Source commit: $COMMIT"
  echo "# Keys: ${#KEYS[@]}"
  echo "# Generated by .ci/update-release-keys.sh. Do not edit by hand."
  for key in "${KEYS[@]}"; do
    echo
    # `awk 1` ends every file with a newline, so no END line can run into
    # the next BEGIN line.
    awk 1 "$key"
  done
} >release-keys/keys.asc

cp "$TMP/src/LICENSE.md" release-keys/LICENSE.md

echo "release-keys/keys.asc: ${#KEYS[@]} keys from nodejs/release-keys@$COMMIT"
